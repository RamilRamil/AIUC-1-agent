"""Правила обнаружения PII (фича 004, A006) — ЕДИНСТВЕННЫЙ источник.

Вынесено в отдельный модуль без зависимостей намеренно: PII маскируется в двух местах —
в ответе агента (``guardrails/output.py``) и в журнале (``trace/writer.py``). Держать правила в
``guardrails/policy.py`` нельзя: ``writer → policy → target.tools → trace.sink → writer`` даёт
цикл импортов. Дублировать регулярки в двух местах — тем более (урок FR-010 фичи 003: три копии
определения «запрещённого инструмента» разъехались бы тихо).

ГРАНИЦЫ (contracts/detectors.md, FR-011): ловятся КАНОНИЧНЫЕ формы. Не покрыты: нестандартные
записи, транслитерация, склейка без разделителей, имена и адреса (их не выразить регуляркой без
ML), PII, распределённая по нескольким текстам. Детектор ловит то, подо что написан.
"""

from __future__ import annotations

import re

PII_MASK = "[PII]"

# Учебные паттерны PII. Порядок важен: карта проверяется до телефона, иначе 16 цифр могли бы
# частично съесться телефонным паттерном.
PII_PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    ("email", re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]+\b")),
    # Карта: 16 цифр, опционально по 4 через пробел/дефис.
    ("card", re.compile(r"\b\d{4}[\s\-]?\d{4}[\s\-]?\d{4}[\s\-]?\d{4}\b")),
    # Телефон: +7 999 123-45-67 / 8(999)1234567 и подобное.
    ("phone", re.compile(r"(?:\+7|\b8)[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}\b")),
]


def find_pii(text: str) -> list[str]:
    """Какие классы PII найдены — для журналирования причины (Принцип V)."""
    return [name for name, pat in PII_PATTERNS if pat.search(text)]


def redact_pii(text: str) -> tuple[str, bool]:
    """Замаскировать PII. Возвращает (текст, изменялся ли).

    Текст без PII MUST остаться неизменным (FR-006): ложные срабатывания ломали бы benign-задачи
    и воспроизводимость.
    """
    original = text
    for _name, pat in PII_PATTERNS:
        text = pat.sub(PII_MASK, text)
    return text, text != original
